export function searchLocations(query: string): string[] {
  const clean = query.trim().toLowerCase();
  if (!clean) return [];

  const matches = ALL_INDIA_LOCATIONS.filter((loc) => {
    if (loc.displayName.toLowerCase().includes(clean)) return true;
    return loc.keywords.some((kw) => kw.includes(clean));
  });

  return matches.slice(0, 12).map((m) => m.displayName);
}
